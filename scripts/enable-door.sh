#!/usr/bin/env bash
# Turn on the PowerEdge door: n2link admin auth with ONE break-glass user ("operator", deployer
# role, random password, bcrypt-hashed in the config), so the normal way in is the pay-to-enter
# pass at /poweredge-app/login. Idempotent. Never writes admin:admin.
#
#   scripts/enable-door.sh          enable (creates secrets/operator.password on first run)
#   scripts/enable-door.sh --off    remove the [admin] section again (open editor, loopback only)
#
# With the door on, n2link also records every outbound connection (egress mode "observe": logged,
# never blocked) and shows the policy in Settings -> "n2link". Door-pass users (role deployer) can
# read it; changing it needs config.write, which no user here has: only the config file can.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TOML="$ROOT/datadirs/n2link/n2linkd.toml"
PASS_FILE="$ROOT/secrets/operator.password"
BCRYPT="$ROOT/n2link/3rd-party/node-red/node_modules/bcryptjs"
[[ -f "$TOML" ]] || { echo "no n2link config at $TOML (run scripts/run-n2link.sh once)" >&2; exit 1; }
[[ -d "$BCRYPT" ]] || { echo "bcryptjs not found; run scripts/setup-editor.sh first" >&2; exit 1; }

strip_admin() {  # remove a previously generated block
  python3 - "$TOML" <<'EOF'
import re, sys, pathlib
p = pathlib.Path(sys.argv[1]); s = p.read_text()
s = re.sub(r"\n# --- PowerEdge door \(generated by scripts/enable-door.sh\) ---\n.*?# --- end PowerEdge door ---\n", "\n", s, flags=re.S)
p.write_text(s)
EOF
}

set_key() {  # set_key <section> <key> <toml value>: replace the key inside that section (must exist)
  python3 - "$TOML" "$1" "$2" "$3" <<'EOF'
import re, sys, pathlib
path, section, key, value = sys.argv[1:5]
p = pathlib.Path(path); s = p.read_text()
m = re.search(rf"(?ms)^\[{re.escape(section)}\]\n(.*?)(?=^\[|\Z)", s)
if not m:
    sys.exit(f"[{section}] not found in {path}")
body, n = re.subn(rf"(?m)^{re.escape(key)}\s*=.*$", f"{key} = {value}", m.group(1), count=1)
if n == 0:
    body = f"{key} = {value}\n" + body
p.write_text(s[:m.start(1)] + body + s[m.end(1):])
EOF
}

if [[ "${1:-}" == "--off" ]]; then
  strip_admin
  set_key config_editor enabled false   # n2link refuses to start with the pane on and login off
  echo "door off: n2link admin auth removed from $TOML (restart n2link)"; exit 0
fi

if [[ ! -f "$PASS_FILE" ]]; then
  mkdir -p "$(dirname "$PASS_FILE")"; chmod 700 "$(dirname "$PASS_FILE")"
  (umask 077; openssl rand -base64 24 | tr -d '/+=' | cut -c1-28 > "$PASS_FILE")
  echo "created break-glass password at secrets/operator.password (git-ignored, 0600)"
fi
HASH="$(node -e "const b=require(process.argv[1]); const fs=require('fs'); process.stdout.write(b.hashSync(fs.readFileSync(process.argv[2],'utf8').trim(), 8))" "$BCRYPT" "$PASS_FILE")"

strip_admin
cat >> "$TOML" <<EOF

# --- PowerEdge door (generated by scripts/enable-door.sh) ---
# Normal entry is the pay-to-enter pass (/poweredge-app/login). This single user is the
# break-glass fallback; its password lives only in secrets/operator.password.
[admin]
[[admin.users]]
username = "operator"
password = "$HASH"
role = "deployer"
# --- end PowerEdge door ---
EOF
set_key egress mode '"observe"'          # record every outbound connection, block nothing
set_key config_editor enabled true      # Settings -> "n2link": read-only for door-pass users
echo "door on: admin auth enabled with user 'operator' (deployer); egress observe; config pane on (read-only for deployers)."
echo "Restart n2link: scripts/demo-up.sh stop && scripts/demo-up.sh"
