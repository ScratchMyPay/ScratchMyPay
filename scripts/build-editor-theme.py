#!/usr/bin/env python3
"""Build the PowerEdge editor theme from Node-RED's own dark theme.

Takes Node-RED's dark palette (dark-colors.scss), swaps in the "Satoshi of Live Music" palette
(Bitcoin orange on near-black), and compiles Node-RED's dark-theme.scss with it. Keeps every
surface Node-RED themes (and its WCAG AA work); only colours change.

Output: n2link/assets/theme/poweredge-dark.css (copied into the editor by n2link's build.rs).
Run:    scripts/build-editor-theme.py        (needs the node-red submodule + its node_modules)
"""
from __future__ import annotations

import logging
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NR = ROOT / "n2link" / "3rd-party" / "node-red"
SASS_DIR = NR / "packages" / "node_modules" / "@node-red" / "editor-client" / "src" / "sass"
SASS_BIN = NR / "node_modules" / ".bin" / "sass"
OUT = ROOT / "n2link" / "assets" / "theme" / "poweredge-dark.css"
LOG = logging.getLogger("build-editor-theme")

# Satoshi of Live Music tokens
BTC, BTC_HOVER, BTC_ACTIVE = "#F7931A", "#ffa940", "#d97b0b"
INK, DIM, LINE = "#F4EFE6", "#9a948a", "#2a2622"
CYAN, GREEN, MAG, YELLOW, RED = "#3CF2FF", "#39FF88", "#FF1F8E", "#ffe600", "#ff5a5a"

# `$name: value;` assignments to replace (only the value changes)
ASSIGN = {
    "form-input-focus-color": BTC, "accent-hover": BTC_HOVER, "accent-active": BTC_ACTIVE,
    "canvas-bg": "#050505", "bg-0": "#030303", "bg-1": "#0c0b0a", "bg-2": "#121110",
    "bg-3": "#191715", "bg-4": "#221f1c", "border-1": LINE, "border-2": "#34302a",
    "neutral-mid": DIM, "text-primary": INK, "text-header": INK, "text-secondary": "#cfc8bc",
    "text-tertiary": DIM, "text-disabled": "#6e685f",
    "secondary-background-inactive": "#0f0e0d", "secondary-background-disabled": "#0e0d0c",
    "tertiary-background": "#100f0e",
    "text-color-error": RED, "text-color-warning": YELLOW, "text-color-success": GREEN,
    "text-color-code": CYAN, "text-color-markdown-alert-important": MAG,
    "text-editor-selection-background": "#3a2408",
    "workspace-button-color-primary": "#050505", "workspace-button-background-primary": BTC,
    "deploy-button-color": "#050505", "deploy-button-background": BTC,
    "view-grid-color": "#1c1916", "view-navigator-background": "rgba(5, 5, 5, 0.9)",
    "view-lasso-fill": "rgba(247, 147, 26, 0.12)",
    "node-status-changed-border": "#0a7f8a", "node-status-changed-background": CYAN,
}
# Remaining literal colours (status dots, debug, diff, code editor) mapped across the file
LITERAL = {"#00d4c8": CYAN, "#4cc38a": GREEN, "#ff6369": RED, "#ffcb47": YELLOW,
           "#f1a10d": "#ffb000", "#bb0000": BTC}


def recolour(src: str) -> str:
    for name, value in ASSIGN.items():
        src, n = re.subn(rf"(^\${re.escape(name)}:\s*)[^;]+;", rf"\g<1>{value};", src, flags=re.M)
        if n != 1:
            raise SystemExit(f"palette variable ${name} matched {n} times; Node-RED changed its dark palette")
    for old, new in LITERAL.items():
        src = re.sub(re.escape(old), new, src, flags=re.I)
    return src


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    for path in (SASS_DIR / "dark-colors.scss", SASS_DIR / "dark-theme.scss", SASS_BIN):
        if not path.exists():
            LOG.error("missing %s (run scripts/setup-editor.sh first)", path)
            return 1
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        (work / "poweredge-colors.scss").write_text(recolour((SASS_DIR / "dark-colors.scss").read_text()))
        theme = (SASS_DIR / "dark-theme.scss").read_text()
        if '@use "dark-colors" as dc;' not in theme:
            raise SystemExit("dark-theme.scss no longer imports dark-colors; update this script")
        (work / "poweredge-theme.scss").write_text(theme.replace('@use "dark-colors"', '@use "poweredge-colors"'))
        OUT.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run([str(SASS_BIN), "--no-source-map", "--style=compressed", f"--load-path={work}",
                        f"--load-path={SASS_DIR}", str(work / "poweredge-theme.scss"), str(OUT)], check=True)
    header = ("/* PowerEdge editor theme: Node-RED dark theme (Apache-2.0) recoloured with the Satoshi of Live Music "
              "palette. Generated by scripts/build-editor-theme.py; do not edit. */\n")
    OUT.write_text(header + OUT.read_text())
    LOG.info("wrote %s (%d bytes, %d variables)", OUT.relative_to(ROOT), OUT.stat().st_size,
             len(re.findall(r"--red-ui-[\w-]+:", OUT.read_text())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
